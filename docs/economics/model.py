#!/usr/bin/env python3
"""Wadeh monthly cost scenarios. Every input is listed with its source/status. Run: python3 model.py > costs.md
Status: V = verified from a dated vendor source; E = engineering estimate (not a quote); Q = needs a vendor quote; H = hypothesis to test."""
FX_EGP_PER_USD = (50.0, "H", "Assumed planning rate; replace with CBE rate on the budgeting date")
A = {  # name: (value, status, note)
 "searches_per_mau": (25, "H", "list/search API calls per monthly active buyer"),
 "details_per_mau": (15, "H", "detail views"),
 "routes_per_mau": (4, "H", "route requests (own pgRouting; compute only)"),
 "assist_explain_per_mau": (3, "H", "LLM explanation calls; parsing is deterministic and free"),
 "llm_in_tokens": (3000, "E", "grounded context per explanation"),
 "llm_out_tokens": (400, "E", ""),
 "llm_in_usd_per_mtok": (2.00, "V", "Claude Sonnet 5.5 input, Anthropic price table cached 2026-11-03"),
 "llm_out_usd_per_mtok": (10.00, "V", "Claude Sonnet 5.5 output, same source"),
 "tile_loads_per_mau": (60, "H", "vector tile requests; OpenFreeMap public = $0 but no SLA"),
 "viewing_requests_per_mau": (0.15, "H", "share of buyers requesting a viewing per month"),
 "ack_rate": (0.6, "H", "partner acknowledges within SLA"),
 "verified_offers_per_supplier": (60, "H", "active offers per pilot supplier"),
}
SCEN = {"pilot": dict(mau=1_000, suppliers=5), "10k": dict(mau=10_000, suppliers=25), "100k": dict(mau=100_000, suppliers=150)}
INFRA = {  # monthly USD ranges (E = estimate, needs quote)
 "pilot": (120, 300, "E", "1 app VM + managed Postgres/PostGIS + object storage + backups"),
 "10k": (350, 900, "E", "2 app VMs, larger DB, replica, CDN"),
 "100k": (1500, 4500, "E", "autoscaled app tier, HA Postgres, self-hosted tiles (PMTiles) + CDN egress"),
}
LABOUR = {  # verification/supplier ops FTE (H) and loaded monthly EGP cost per FTE (Q)
 "ops_fte_per_supplier": (0.08, "H", "weekly sheet review, disputes, gate verification"),
 "fte_monthly_egp": (None, "Q", "founder to set from local salary benchmarks"),
}
def v(k): return A[k][0]
out = ["# Monthly cost scenarios (generated by docs/economics/model.py, 2026-11-23)", "",
       "Not a forecast. Scenarios to see which line dominates and where the economics break. **Status:** V verified (dated source), E estimate, Q needs quote, H hypothesis.", "",
       "| Scenario | MAU | LLM usd | Infra usd (range) | Ops FTE | Viewing requests | Acknowledged viewings | Infra+LLM per MAU (usd) | per acknowledged viewing (usd) | per verified offer-month (usd) |",
       "|---|---|---|---|---|---|---|---|---|---|"]
for name, s in SCEN.items():
    mau = s["mau"]
    llm = mau * v("assist_explain_per_mau") * (v("llm_in_tokens") * v("llm_in_usd_per_mtok") + v("llm_out_tokens") * v("llm_out_usd_per_mtok")) / 1e6
    lo, hi, _, _ = INFRA[name]
    fte = s["suppliers"] * LABOUR["ops_fte_per_supplier"][0]
    req = mau * v("viewing_requests_per_mau"); ack = req * v("ack_rate")
    offers = s["suppliers"] * v("verified_offers_per_supplier")
    out.append(f"| {name} | {mau:,} | {llm:,.0f} | {lo:,}–{hi:,} | {fte:.1f} | {req:,.0f} | {ack:,.0f} | {(lo+llm)/mau:.3f}–{(hi+llm)/mau:.3f} | {(lo+llm)/ack:.2f}–{(hi+llm)/ack:.2f} + ops | {(lo+llm)/offers:.2f}–{(hi+llm)/offers:.2f} + ops |")
out += ["", "Ops labour is listed as FTE, not money, because the loaded EGP cost per FTE needs the founder's input (Q). At pilot scale, **ops labour, not software, is expected to dominate** cost per acknowledged viewing.", "",
        "## Inputs", "", "| Input | Value | Status | Note |", "|---|---|---|---|"]
for k, (val, st, note) in {**A, **LABOUR, "fx_egp_per_usd": FX_EGP_PER_USD}.items(): out.append(f"| {k} | {val} | {st} | {note} |")
out += ["", "| Infra scenario | USD/month | Status | Scope |", "|---|---|---|---|"] + [f"| {k} | {lo}–{hi} | {st} | {n} |" for k, (lo, hi, st, n) in INFRA.items()]
out += ["", "## Unpriced (must be quoted before launch)", "- SMS/WhatsApp Business messaging for partner and buyer notifications (per-conversation pricing varies by country and category).",
        "- Commercial map/geocoding if OpenFreeMap or self-hosting is not acceptable (Google Maps Platform, HERE, Mapbox: quote at 10k/100k MAU).",
        "- Live or typical traffic data (no provider contracted; product works without it and says so).", "- PDPC licence fees and counsel time (L-01, L-02).", "- Play developer account, domain and trademark filing.",
        "", "## Where the economics stop working (stated as testable conditions)",
        "1. If acknowledged viewings per month stay below ~0.5% of MAU, cost per acknowledged viewing exceeds what any per-viewing fee can recover. Watch `ack_rate × viewing_requests_per_mau`.",
        "2. If one ops FTE cannot keep more than ~12 suppliers fresh (weekly sheets, disputes, gate checks), supply cost grows linearly with coverage. Hypothesis H-04 tests whether stale-stock feedback lowers this.",
        "3. LLM spend is small at these assumptions (deterministic parsing, explanation only on demand). It becomes material only if explanations rise above ~30 per MAU. Kill switch and spend cap exist (`provider_switch`)."]
print("\n".join(out))
